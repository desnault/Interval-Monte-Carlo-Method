if __name__ == "__main__":

    # -------------------------------------------------------------------------
    # PARSE USER ARGUMENTS
    # -------------------------------------------------------------------------

    script_dir = Path(__file__).resolve().parent

    parser = argparse.ArgumentParser(description="Generate and export deterministic and stochastic Dubins-car trajectories for the OCEANS 2025 scenario.")

    parser.add_argument("--num-samples", type=int, default=500, help="Number of noisy simulations to generate and export (default: 500).")
    parser.add_argument("--output-dir", type=str, default="oceans2025", help="Name of the output directory created inside the output path (default: oceans2025).")
    parser.add_argument("--output-path", type=str, default=str(script_dir), help="Path where the output directory must be created (default: directory of this script).")
    parser.add_argument("--seed", type=int, default=8734942, help="Seed of the random generator used for reproducible trajectory generation (default: 8734942).")
    parser.add_argument("--debug", action="store_true", help="Enable debug mode: display detailed execution information and a trajectory plot.")

    args = parser.parse_args()

    # -------------------------------------------------------------------------
    # CHECK USER ARGUMENTS
    # -------------------------------------------------------------------------

    if args.num_samples <= 0:
        raise ValueError("main.py: --num-samples must be strictly greater than 0.")

    if args.seed <= 0:
        raise ValueError("main.py: --seed must be strictly greater than 0.")

    if args.debug:
        print("\n[DEBUG] Script parameters:")
        print(f"\t- Number of samples: {args.num_samples}")
        print(f"\t- Output directory: {args.output_dir}")
        print(f"\t- Output path: {args.output_path}")
        print(f"\t- Random seed: {args.seed}")
        print(f"\t- Debug mode: {args.debug}")

    # -------------------------------------------------------------------------
    # CHECK OUTPUT PATH AND CREATE DIRECTORIES
    # -------------------------------------------------------------------------

    output_path = Path(args.output_path)

    if not output_path.exists():
        raise FileNotFoundError(f"main.py: output path does not exist: {output_path}")

    if not output_path.is_dir():
        raise NotADirectoryError(f"main.py: output path is not a directory: {output_path}")

    output_directory_path = output_path / args.output_dir

    if output_directory_path.exists():
        raise RuntimeError(f"main.py: output directory already exists: {output_directory_path}")

    output_directory_path.mkdir()

    perfect_directory_path = output_directory_path / "Perfect"
    noisy_directory_path = output_directory_path / "Noisy"

    perfect_directory_path.mkdir()
    noisy_directory_path.mkdir()

    # -------------------------------------------------------------------------
    # GLOBAL PARAMETERS
    # -------------------------------------------------------------------------

    random_generator = np.random.default_rng(args.seed)

    # Gaussian noise applied to the heading command
    heading_noise_mean = 0.0
    heading_noise_std = np.pi/50.0

    # Simulation parameters
    duration = 30.0
    time_step = 0.05

    # Initial state [x0, y0, heading0, speed0]
    initial_state = (0.0, 0.0, 0.0, 0.0)

    if args.debug:
        print("\n[DEBUG] Simulation parameters:")
        print(f"\t- Mission duration: {duration} s")
        print(f"\t- Integration time step: {time_step} s")
        print(f"\t- Initial state vector: {initial_state}")
        print(f"\t- Heading noise mean: {heading_noise_mean}")
        print(f"\t- Heading noise standard deviation: {heading_noise_std}")

    # -------------------------------------------------------------------------
    # GENERATE PERFECT REFERENCE TRAJECTORY
    # -------------------------------------------------------------------------

    perfect_dubins_car = MyCustomDubinsCar(
        initial_state_vector=initial_state,
        heading_noise_mean=0.0,
        heading_noise_std=0.0,
        random_generator=np.random.default_rng(0)
    )

    perfect_dubins_car.run_simulation(duration, time_step)
    print("\n[SIMULATION] Reference trajectory generated successfully.")

    export_simulation(perfect_dubins_car, perfect_directory_path, time_step)
    print("[EXPORT] Reference trajectory exported successfully.\n")

    # -------------------------------------------------------------------------
    # OPTIONAL DEBUG FIGURE
    # -------------------------------------------------------------------------

    if args.debug:   
        plt.figure(figsize=(8, 6))

    # -------------------------------------------------------------------------
    # GENERATE AND EXPORT NOISY TRAJECTORIES
    # -------------------------------------------------------------------------

    for i in range(args.num_samples):
        print(f"[SIMULATION] Simulation {i + 1}/{args.num_samples}")

        # Create one independent RNG per trajectory for reproducibility
        simulation_seed = int(random_generator.integers(0, 2**32 - 1))
        simulation_rng = np.random.default_rng(simulation_seed)

        dubins_car = MyCustomDubinsCar(
            initial_state_vector=initial_state,
            heading_noise_mean=heading_noise_mean,
            heading_noise_std=heading_noise_std,
            random_generator=simulation_rng
        )

        dubins_car.run_simulation(duration, time_step, debug_print=args.debug)
        export_simulation(dubins_car, noisy_directory_path, time_step, simulation_number=i + 1)

        print("[EXPORT] Simulation exported successfully.\n")

        if args.debug:
            trajectory = np.array(dubins_car.state_vector_trajectory)
            plt.plot(trajectory[:, 0], trajectory[:, 1], alpha=0.7, zorder=0)

    # -------------------------------------------------------------------------
    # DEBUG DISPLAY
    # -------------------------------------------------------------------------

    if args.debug:
        perfect_trajectory = np.array(perfect_dubins_car.state_vector_trajectory)

        plt.plot(
            perfect_trajectory[:, 0],
            perfect_trajectory[:, 1],
            color="black",
            linewidth=2,
            zorder=10,
            label="Reference trajectory"
        )

        plt.xlabel("x axis (m)")
        plt.ylabel("y axis (m)")
        plt.title("Generated Dubins-car trajectories for the OCEANS 2025 scenario")
        plt.grid(True)
        plt.axis("equal")
        plt.legend()
        plt.tight_layout()
        plt.show()

    print(f"[DONE] Generated and exported {args.num_samples} noisy trajectory sample(s) in: {output_directory_path}")