# =============================================================================
# CUSTOM DUBINS CAR CLASS
# =============================================================================

class MyCustomDubinsCar(DubinsCar):
    """
    Custom Dubins-car model used to generate the OCEANS 2025 trajectory dataset.

    This class defines:
        - a nominal speed regulator,
        - a time-dependent heading command,
        - an additive Gaussian noise model on the heading command.

    The resulting noisy trajectories progressively drift away from the nominal
    reference trajectory, which mimics the behavior of a robot affected by
    dead-reckoning navigation uncertainty.
    """

    def __init__(self, initial_state_vector=(0.0, 0.0, 0.0, 0.0), heading_noise_mean=0.0, heading_noise_std=0.0, random_generator=None):
        """
        Initialize the custom Dubins-car model.

        Args:
            initial_state_vector (tuple, list, or np.ndarray, optional):
                Initial state [x0, y0, heading0, speed0].

            heading_noise_mean (float, optional):
                Mean of the Gaussian noise added to the heading command.

            heading_noise_std (float, optional):
                Standard deviation of the Gaussian noise added to the heading command.

            random_generator (np.random.Generator, optional):
                NumPy random number generator used to draw heading noise.
        """
        super().__init__(initial_state_vector)

        self.heading_noise_mean = float(heading_noise_mean)
        self.heading_noise_std = float(heading_noise_std)

        if random_generator is None:
            self.random_generator = np.random.default_rng()
        else:
            self.random_generator = random_generator

    def compute_command_vector(self, state_vector, simulation_time):
        """
        Compute the command vector applied to the Dubins car.

        The speed is regulated toward a constant desired value.
        The heading command is a smooth time-dependent function designed to
        generate a long survey-like trajectory. A Gaussian perturbation is added
        to the heading command in order to create stochastic trajectory realizations.

        Args:
            state_vector (np.ndarray):
                Current state [x, y, heading, speed].

            simulation_time (float):
                Current simulation time.

        Returns:
            np.ndarray:
                Command vector [heading_rate, acceleration].
        """
        # Get current state variables
        px, py, heading, speed = np.array(state_vector, dtype=float).flatten()

        # Speed regulator
        desired_speed = 2.0
        speed_gain = 1.0
        acceleration = speed_gain * (desired_speed - speed)

        # Nominal heading command
        heading_rate_nominal = 0.08 * np.sin(0.18 * simulation_time) + 0.03 * np.sin(0.55 * simulation_time)

        # Stochastic perturbation
        heading_noise = self.random_generator.normal(self.heading_noise_mean, self.heading_noise_std)
        heading_rate_noisy = heading_rate_nominal + heading_noise

        # Return command vector
        return np.array([heading_rate_noisy, acceleration], dtype=float)

    def mission_is_completed(self, state_vector, simulation_time):
        """
        Mission completion criterion.

        In this trajectory-generation script, the simulation always runs until the
        maximal simulation duration is reached.

        Args:
            state_vector (np.ndarray):
                Current state [x, y, heading, speed].

            simulation_time (float):
                Current simulation time.

        Returns:
            bool:
                Always False.
        """
        return False


# =============================================================================
# EXPORT FUNCTION
# =============================================================================

def export_simulation(dubins_car: DubinsCar, output_directory: Path, time_step: float, simulation_number: int = None):
    """
    Export a Dubins-car simulation to disk.

    Two files are generated:
        1) a text file containing the sampled trajectory:
           [t, x, y, theta, v]

        2) a serialized CODAC TubeVector (.tubevector) for direct use in the
           downstream C++ interval-based pipeline.

    Args:
        dubins_car (DubinsCar):
            Simulated Dubins-car instance containing recorded trajectories.

        output_directory (Path):
            Directory where the exported files will be written.

        time_step (float):
            Integration time step used to build the TubeVector.

        simulation_number (int, optional):
            Identifier for noisy simulations. If None, generic filenames are used
            (typically for the perfect/reference trajectory).

    Raises:
        ValueError:
            If the recorded trajectory is empty or has inconsistent dimensions.
    """
    
    # Extract trajectories
    time_trajectory = np.array(dubins_car.time_trajectory, dtype=float)
    state_trajectory = np.array(dubins_car.state_vector_trajectory, dtype=float)

    # Verify format
    if time_trajectory.size == 0 or state_trajectory.size == 0:
        raise ValueError("export_simulation(): empty trajectory, nothing to export.")

    if state_trajectory.ndim != 2 or state_trajectory.shape[1] != 4:
        raise ValueError("export_simulation(): state_trajectory must have shape (N, 4).")

    if time_trajectory.shape[0] != state_trajectory.shape[0]:
        raise ValueError("export_simulation(): time and state trajectories must have the same length.")

    # Build export array
    # Exported text format: [t, x, y, theta, v]
    simulation_trajectory = np.hstack((time_trajectory[:, np.newaxis], state_trajectory))

    # Define output filenames
    if simulation_number is None:
        numpy_array_filename = output_directory / "simulation_numpy_array.txt"
        tubevector_filename = output_directory / "simulation.tubevector"
    else:
        numpy_array_filename = output_directory / f"simulation{simulation_number}_numpy_array.txt"
        tubevector_filename = output_directory / f"simulation{simulation_number}.tubevector"

    # Export text file
    np.savetxt(numpy_array_filename, simulation_trajectory, header="t x y theta v")

    # Build codac tubevector
    codac_trajectory_vector = codac.TrajectoryVector(4)
    codac_trajectory_vector[0] = codac.Trajectory(time_trajectory, state_trajectory[:, 0])
    codac_trajectory_vector[1] = codac.Trajectory(time_trajectory, state_trajectory[:, 1])
    codac_trajectory_vector[2] = codac.Trajectory(time_trajectory, state_trajectory[:, 2])
    codac_trajectory_vector[3] = codac.Trajectory(time_trajectory, state_trajectory[:, 3])
    codac_tube_vector = codac.TubeVector(codac_trajectory_vector, time_step)

    # Export codac tubevector
    codac_tube_vector.serialize(str(tubevector_filename))


