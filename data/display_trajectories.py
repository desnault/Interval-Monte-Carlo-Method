# =============================================================================
# IMPORT LIBRARIES
# =============================================================================

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


# =============================================================================
# HELPER FUNCTION
# =============================================================================

def load_trajectories_in_directory(directory_path: Path):
    """
    Load all trajectory files stored as .txt arrays in a directory.

    The files are loaded in lexicographic order to ensure reproducible display.

    Args:
        directory_path (Path):
            Path to the directory containing trajectory files.

    Returns:
        list[np.ndarray]:
            List of loaded trajectories.

    Raises:
        FileNotFoundError:
            If the directory does not exist.

        NotADirectoryError:
            If the provided path is not a directory.

        RuntimeError:
            If no .txt trajectory file is found in the directory.

        ValueError:
            If a file cannot be loaded as a numeric array.
    """
    if not directory_path.exists():
        raise FileNotFoundError(f"Directory does not exist: {directory_path}")

    if not directory_path.is_dir():
        raise NotADirectoryError(f"Path is not a directory: {directory_path}")

    txt_files = sorted([file for file in directory_path.glob("*.txt") if file.is_file()])

    if len(txt_files) == 0:
        raise RuntimeError(f"No trajectory file with '.txt' extension was found in directory: {directory_path}")

    trajectory_list = []

    for file_path in txt_files:
        try:
            trajectory = np.loadtxt(file_path)
        except Exception as exc:
            raise ValueError(f"Unable to load trajectory file: {file_path}") from exc

        trajectory_list.append(trajectory)

    return trajectory_list


# =============================================================================
# MAIN
# =============================================================================

if __name__ == "__main__":

    # -------------------------------------------------------------------------
    # PARSE USER ARGUMENTS
    # -------------------------------------------------------------------------

    # Path of the current script
    script_dir = Path(__file__).resolve().parent

    parser = argparse.ArgumentParser(
        description="Display the trajectories generated for the OCEANS 2025 Dubins-car scenario."
    )

    parser.add_argument(
        "--traj-dir",
        type=str,
        default="oceans2025",
        help="Name of the directory containing the exported trajectories (default: oceans2025)."
    )

    parser.add_argument(
        "--traj-path",
        type=str,
        default=str(script_dir),
        help="Path to the parent directory containing the trajectory folder (default: directory of this script)."
    )

    args = parser.parse_args()

    # -------------------------------------------------------------------------
    # CHECK PATHS
    # -------------------------------------------------------------------------

    base_path = Path(args.traj_path)

    if not base_path.exists():
        raise FileNotFoundError(f"Base path does not exist: {base_path}")

    if not base_path.is_dir():
        raise NotADirectoryError(f"Base path is not a directory: {base_path}")

    traj_directory_path = base_path / args.traj_dir

    if not traj_directory_path.exists():
        raise FileNotFoundError(f"Trajectory directory does not exist: {traj_directory_path}")

    if not traj_directory_path.is_dir():
        raise NotADirectoryError(f"Trajectory path is not a directory: {traj_directory_path}")

    perfect_directory_path = traj_directory_path / "Perfect"
    noisy_directory_path = traj_directory_path / "Noisy"

    # -------------------------------------------------------------------------
    # LOAD TRAJECTORIES
    # -------------------------------------------------------------------------

    perfect_trajectories = load_trajectories_in_directory(perfect_directory_path)
    noisy_trajectories = load_trajectories_in_directory(noisy_directory_path)

    if len(perfect_trajectories) == 0:
        raise RuntimeError(f"No perfect trajectory was loaded from: {perfect_directory_path}")

    perfect_trajectory = perfect_trajectories[0]

    print(f"[INFO] Loaded {len(perfect_trajectories)} perfect trajectory file(s) from: {perfect_directory_path}")
    print(f"[INFO] Loaded {len(noisy_trajectories)} noisy trajectory file(s) from: {noisy_directory_path}")

    # -------------------------------------------------------------------------
    # DISPLAY TRAJECTORIES
    # -------------------------------------------------------------------------

    plt.figure(figsize=(8, 6))

    # Display all noisy trajectories
    for trajectory in noisy_trajectories:
        trajectory = np.array(trajectory)
        plt.plot(trajectory[:, 4], trajectory[:, 5], alpha=0.7, zorder=0)

    # Display the perfect trajectory on top
    plt.plot(
        perfect_trajectory[:, 4],
        perfect_trajectory[:, 5],
        color="black",
        linewidth=2,
        zorder=10,
        label="Trajectory without noise"
    )

    plt.xlabel("x axis (m)")
    plt.ylabel("y axis (m)")
    plt.title("Generated Dubins-car trajectories for the OCEANS 2025 scenario")
    plt.grid(True)
    plt.axis("equal")
    plt.legend()
    plt.tight_layout()
    plt.show()